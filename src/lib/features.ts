// 배포 전 미완성 기능을 감추는 스위치 (#140).
//
// 코드를 지웠다 되살리는 대신 환경변수로 켜고 끈다 — 로컬은 켜서 개발하고,
// 배포는 값을 넣지 않아 자동으로 꺼진다.
//
// 규칙: **값이 없으면 꺼진다.** "true"라고 명시할 때만 켜지므로, 배포 설정에
// 깜빡 넣지 않아도 미완성 기능이 사용자에게 노출되지 않는다(안전한 쪽으로 실패).
//
// NEXT_PUBLIC_* 이므로 클라이언트와 서버 양쪽에서 같은 값을 읽는다 — 화면과
// API 라우트를 스위치 하나로 함께 막을 수 있다. 단 빌드 시점에 번들로 박히므로
// (Dockerfile 주석 참고) 켤 때는 Dockerfile의 ARG/ENV와 deploy.yml의
// build-args에도 값을 넘겨야 한다. 끄는 동안은 어느 쪽도 손댈 필요가 없다.
//
// 이 파일은 next/server 등 서버 전용 모듈을 import하지 않는다 — 클라이언트
// 컴포넌트에서도 그대로 가져다 쓰기 때문이다.

/** 비드봇(챗봇). 백엔드 에이전트가 미완성이라 기본 비활성. */
export const BIDBOT_ENABLED = process.env.NEXT_PUBLIC_BIDBOT_ENABLED === "true";

/**
 * 맞춤추천에서 "확인필요"·"보완가능" 판정까지 보여줄지.
 *
 * 판정 로직이 신뢰할 수준이 될 때까지는 "가능"만 노출한다. 다만 목록에서
 * 걸러내는 일은 백엔드가 해야 한다 — 화면에서 걸러내면 서버가 준 total과
 * 페이지 수가 어긋난다(reco-view의 주석 참고). 백엔드에 판정 필터
 * 파라미터가 붙으면 이 스위치로 분기한다.
 */
export const SHOW_ALL_VERDICTS = process.env.NEXT_PUBLIC_SHOW_ALL_VERDICTS === "true";
